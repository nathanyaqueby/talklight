function t(s, v) {
  let r = (LANG === "de" && DE[s]) || s;
  if (v) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in v ? v[k] : m));
  return r;
}

const _textRec = new WeakMap();
const _attrRec = new WeakMap();

function translateTree(root) {
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = w.nextNode())) {
    const p = n.parentElement;
    if (!p || p.closest("script,style")) continue;
    const rec = _textRec.get(n);
    const orig = rec && n.data === rec.shown ? rec.en : n.data;     // text changed by the app = new original
    const m = orig.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!m[2]) continue;
    const out = m[1] + t(m[2].replace(/\s+/g, " ")) + m[3];
    _textRec.set(n, { en: orig, shown: out });
    if (out !== n.data) n.data = out;
  }
  const sel = TRANSLATED_ATTRS.map((a) => "[" + a + "]").join(",");
  root.querySelectorAll(sel).forEach((el) => {
    const rec = _attrRec.get(el) || {};
    TRANSLATED_ATTRS.forEach((a) => {
      if (!el.hasAttribute(a)) return;
      const cur = el.getAttribute(a);
      const en = rec[a] && cur === rec[a].shown ? rec[a].en : cur;
      const out = t(en);
      rec[a] = { en, shown: out };
      if (out !== cur) el.setAttribute(a, out);
    });
    _attrRec.set(el, rec);
  });
}

function setLangCode(code) {
  LANG = code === "de" ? "de" : "en";
  document.documentElement.lang = LANG;
  translateTree(document.body);
}
